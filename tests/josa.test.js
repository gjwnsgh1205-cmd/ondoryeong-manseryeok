/* josa.js — 물상 열 개 전부에 대해 조사가 맞는지 본다.
   검수가 잡은 실제 깨짐("바다이 하나 더", "무쇠이 닿는", "산마루이 제 자리를")이
   다시 나오지 않는지가 핵심이다. */
'use strict';
const J = require('../js/josa.js');

let pass = 0, fail = 0;
const eq = (got, want, name) => {
  if (got === want) { pass++; return; }
  fail++;
  console.log('  ✗ ' + name + '\n      나온 것: ' + got + '\n      바랄 것: ' + want);
};

/* 물상 열 개 — 받침 있는 것과 없는 것이 섞여 있다 */
const 물상 = ['큰 나무', '풀꽃', '햇살', '등불', '산마루', '들녘', '무쇠', '보석', '바다', '이슬'];
const 은는 = ['큰 나무는', '풀꽃은', '햇살은', '등불은', '산마루는', '들녘은', '무쇠는', '보석은', '바다는', '이슬은'];
const 이가 = ['큰 나무가', '풀꽃이', '햇살이', '등불이', '산마루가', '들녘이', '무쇠가', '보석이', '바다가', '이슬이'];
const 으로 = ['큰 나무로', '풀꽃으로', '햇살로', '등불로', '산마루로', '들녘으로', '무쇠로', '보석으로', '바다로', '이슬로'];

물상.forEach((w, i) => {
  eq(J.fill('{물상}은', { 물상: w }), 은는[i], '은/는 — ' + w);
  eq(J.fill('{물상}이', { 물상: w }), 이가[i], '이/가 — ' + w);
  eq(J.fill('{물상}으로', { 물상: w }), 으로[i], '으로/로 — ' + w);
});

/* 검수가 실제로 잡은 문장들 */
eq(J.fill('{물상}이 하나 더 서 있는', { 물상: '바다' }), '바다가 하나 더 서 있는', '검수 지적 1');
eq(J.fill('{물상}이 닿는 자리가', { 물상: '무쇠' }), '무쇠가 닿는 자리가', '검수 지적 2');
eq(J.fill('{물상}이 제 자리를 찾아', { 물상: '산마루' }), '산마루가 제 자리를 찾아', '검수 지적 3');
eq(J.fill('{물상}이에요', { 물상: '들녘' }), '들녘이에요', '이에요 — 받침 있음');
eq(J.fill('{물상}이에요', { 물상: '산마루' }), '산마루예요', '이에요 — 받침 없음');

/* 대표형을 어느 쪽으로 적어도 결과가 같아야 한다 */
eq(J.fill('{물상}는', { 물상: '들녘' }), '들녘은', '대표형이 는 이어도');
eq(J.fill('{물상}가', { 물상: '보석' }), '보석이', '대표형이 가 여도');

/* 이름은 없을 수 있다. 없으면 슬롯만 빠지고 나머지는 살아야 한다. */
eq(J.fill('{이름}님은 지금', { 이름: '유진' }), '유진님은 지금', '이름 있음');
eq(J.fill('{이름}님은 지금', { 이름: '' }), '님은 지금', '이름 없음 — 슬롯만 사라진다');

/* 간지는 한자가 섞인다 */
eq(J.fill('{대운간지}을', { 대운간지: '경술(庚戌)' }), '경술(庚戌)을', '괄호 뒤 한자 — 술(戌)은 받침');
eq(J.fill('{올해간지}는', { 올해간지: '병오(丙午)' }), '병오(丙午)는', '오(午)는 받침 없음');

/* 조사가 아닌 글자가 뒤에 오면 건드리지 않는다 */
eq(J.fill('{물상}처럼', { 물상: '바다' }), '바다처럼', '조사가 아닌 말은 그대로');
eq(J.fill('{물상} 하나', { 물상: '무쇠' }), '무쇠 하나', '띄어쓰기가 있으면 그대로');

/* 모르는 슬롯은 손대지 않는다 */
eq(J.fill('{없는것}은', {}), '{없는것}은', '값이 없는 슬롯은 그대로 둔다');

console.log('\n  ' + pass + ' 통과, ' + fail + ' 실패');
process.exit(fail ? 1 : 0);
